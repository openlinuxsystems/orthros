//! The man(2) pages, in scdoc: one per system call (`radix_send(2)`), one
//! per module of interfaces and types (`radix-memory(2)`), and one for the
//! errors (`radix-errors(2)`).

use std::fmt::Write;

use crate::check::SYSCALL_WORDS;
use crate::{Abi, Call, Dir, Field, Item, ItemKind, Module, Type, camel, summary};

/// The registers of the arguments and results, in order (x86-64).
const REGISTERS: [&str; SYSCALL_WORDS] =
    ["rdi", "rsi", "rdx", "r10", "r8", "r9", "r12", "r13", "r14", "r15"];

/// Generates the pages, as (file name, scdoc text).
pub fn man_pages(abi: &Abi) -> Vec<(String, String)> {
    let mut pages = Vec::new();
    for (module, call) in abi.syscalls() {
        pages.push((format!("radix_{}.2.scd", call.name), syscall_page(abi, module, call)));
    }
    for module in &abi.modules {
        if module.items.iter().all(|item| matches!(item.kind, ItemKind::Syscall(_))) {
            continue;
        }
        pages.push((format!("{}.2.scd", page_name(&module.name)), module_page(abi, module)));
    }
    pages
}

/// The name of a module's page.
pub fn page_name(module: &str) -> String {
    format!("radix-{}", module.replace('_', "-"))
}

/// Escapes text for scdoc and turns `code` into bold.
fn escape(text: &str) -> String {
    let mut out = String::new();
    let mut code = false;
    for c in text.chars() {
        match c {
            '`' => {
                out.push('*');
                code = !code;
            }
            '\\' => out.push_str("\\\\"),
            '*' => out.push_str("\\*"),
            '_' => out.push_str("\\_"),
            _ => out.push(c),
        }
    }
    if code {
        out.push('*');
    }
    out
}

/// Documentation lines as scdoc paragraphs.
fn paragraphs(doc: &[String]) -> String {
    let mut out = String::new();
    for line in doc {
        if line.trim().is_empty() {
            out.push('\n');
        } else {
            out.push_str(&escape(line));
            out.push('\n');
        }
    }
    out
}

fn indented(doc: &[String]) -> String {
    let mut out = String::new();
    for line in doc {
        if !line.trim().is_empty() {
            let _ = writeln!(out, "\t{}", escape(line));
        }
    }
    out
}

fn header(out: &mut String, name: &str, source: &str) {
    let _ = writeln!(out, "{name}(2) \"Dukovo\" \"Dukovo Manual\"\n");
    let _ = writeln!(out, "; Generated by ridlc from {source}. Do not edit.\n");
}

fn lower_first(text: &str) -> String {
    let mut chars = text.chars();
    match chars.next() {
        Some(first) if !text.starts_with("I ") => {
            first.to_lowercase().collect::<String>() + chars.as_str()
        }
        Some(first) => first.to_string() + chars.as_str(),
        None => String::new(),
    }
}

/// How a parameter type reads in a page.
fn type_text(ty: &Type) -> String {
    match ty {
        Type::Prim(prim) => prim.name().into(),
        Type::Slot => "slot".into(),
        Type::Addr => "addr".into(),
        Type::Named(name) => name.clone(),
        Type::Array(inner, len) => format!("[{}; {len}]", type_text(inner)),
        Type::Bytes(Dir::In) => "in bytes".into(),
        Type::Bytes(Dir::Out) => "out bytes".into(),
    }
}

fn signature(fields: &[Field]) -> String {
    let parts: Vec<String> =
        fields.iter().map(|f| format!("{}: {}", f.name, type_text(&f.ty))).collect();
    format!("({})", parts.join(", "))
}

fn c_signature(abi: &Abi, call: &Call, function: &str, method: bool) -> String {
    let mut params = Vec::new();
    if method {
        params.push("uint32_t cap".to_string());
    }
    for field in &call.args {
        params.push(match &field.ty {
            Type::Array(_, len) => format!("const uint64_t {}[{len}]", field.name),
            Type::Bytes(Dir::In) => format!("const void *{0}, size_t {0}_len", field.name),
            Type::Bytes(Dir::Out) => format!("void *{0}, size_t {0}_len", field.name),
            Type::Named(name) => match abi.find(name).map(|(_, i)| &i.kind) {
                Some(ItemKind::Enum { .. }) => {
                    format!("enum radix_{} {}", crate::snake(name), field.name)
                }
                _ => format!("uint64_t {}", field.name),
            },
            Type::Prim(prim) => format!("{} {}", crate::gen_c::prim(*prim), field.name),
            Type::Slot => format!("uint32_t {}", field.name),
            Type::Addr => format!("uint64_t {}", field.name),
        });
    }
    if !call.results.is_empty() {
        params.push(format!("struct {function}_results *results"));
    }
    if params.is_empty() {
        params.push("void".into());
    }
    format!("uint64_t {function}({});", params.join(", "))
}

fn errors_section(out: &mut String, abi: &Abi, raises: &[String]) {
    if raises.is_empty() {
        out.push_str("It cannot fail.\n");
        return;
    }
    for name in raises {
        if let Some(error) = abi.error(name) {
            let _ = writeln!(
                out,
                "*{}* ({})\n{}",
                escape(name),
                error.errno.as_deref().unwrap_or("?"),
                indented(&error.doc)
            );
        }
    }
}

fn syscall_page(abi: &Abi, module: &Module, call: &Call) -> String {
    let name = format!("radix_{}", call.name);
    let mut out = String::new();
    header(&mut out, &name, &module.path);
    let _ = writeln!(
        out,
        "# NAME\n\n{} - {}\n",
        escape(&name),
        escape(&lower_first(&summary(&call.doc)))
    );
    out.push_str("# SYNOPSIS\n\n```\n");
    let _ = writeln!(out, "#include <radix/{}.h>\n", module.name);
    let _ = writeln!(out, "{}", c_signature(abi, call, &name, false));
    out.push_str("```\n\nIn Rust, with the *radix-abi* crate:\n\n```\n");
    let mut args: Vec<String> = vec!["sys".into()];
    args.extend(call.args.iter().map(|f| f.name.clone()));
    let returns =
        if call.results.is_empty() { "()".into() } else { format!("{}Results", camel(&call.name)) };
    let _ = writeln!(
        out,
        "radix_abi::syscalls::{}({}) -> Result<{returns}, Status>\n```\n",
        call.name,
        args.join(", ")
    );
    let _ = writeln!(out, "# DESCRIPTION\n\n{}", paragraphs(&call.doc));
    let _ = writeln!(
        out,
        "# REGISTERS\n\nOn x86-64 the call's number, {}, goes in *rax*, and its status comes back there.\n",
        call.number
    );
    out.push_str("[[ *Register*\n:< *Argument*\n:< *Result*\n");
    let flatten = |fields: &[Field]| -> Vec<String> {
        let mut words = Vec::new();
        for field in fields {
            let count = abi.words(&field.ty);
            match &field.ty {
                Type::Bytes(_) => {
                    words.push(format!("{} (address)", field.name));
                    words.push(format!("{} (length)", field.name));
                }
                _ if count > 1 => {
                    (0..count).for_each(|i| words.push(format!("{}[{i}]", field.name)));
                }
                _ => words.push(field.name.clone()),
            }
        }
        words
    };
    let (args, results) = (flatten(&call.args), flatten(&call.results));
    for (index, register) in REGISTERS.iter().enumerate() {
        let arg = args.get(index).map_or("-".to_string(), |a| escape(a));
        let result = results.get(index).map_or("-".to_string(), |r| escape(r));
        let _ = writeln!(out, "|  *{register}*\n:  {arg}\n:  {result}");
    }
    out.push_str("\n*rcx* and *r11* are overwritten; every other register keeps its value.\n\n");
    out.push_str(
        "# RETURN VALUE\n\n0 on success, otherwise an error status (see *radix-errors*(2)); the C \
                  function returns the status, and *radix_kernel_errno*() maps it to an errno.\n\n",
    );
    out.push_str("# ERRORS\n\n");
    errors_section(&mut out, abi, &call.raises);
    out.push_str("\n# SEE ALSO\n\n*radix-ipc*(7), *radix-capabilities*(7), *radix-errors*(2)\n");
    out
}

fn type_section(out: &mut String, abi: &Abi, item: &Item) {
    match &item.kind {
        ItemKind::Enum { repr, variants } => {
            let _ =
                writeln!(out, "## {} ({})\n\n{}", item.name, repr.name(), paragraphs(&item.doc));
            for variant in variants {
                let _ = writeln!(
                    out,
                    "*{}* = {}\n{}",
                    escape(&variant.name),
                    variant.value,
                    indented(&variant.doc)
                );
            }
        }
        ItemKind::Flags { repr, bits } => {
            let _ = writeln!(
                out,
                "## {} ({}, bit numbers)\n\n{}",
                item.name,
                repr.name(),
                paragraphs(&item.doc)
            );
            for bit in bits {
                let _ = writeln!(
                    out,
                    "*{}* = bit {}\n{}",
                    escape(&bit.name),
                    bit.value,
                    indented(&bit.doc)
                );
            }
        }
        ItemKind::Struct { fields } => {
            let (size, _) = abi.layout(&Type::Named(item.name.clone())).unwrap_or((0, 1));
            let _ = writeln!(out, "## {} ({size} bytes)\n\n{}", item.name, paragraphs(&item.doc));
            let mut offset: usize = 0;
            for field in fields {
                let (field_size, align) = abi.layout(&field.ty).unwrap_or((0, 1));
                offset = offset.next_multiple_of(align);
                let _ = writeln!(
                    out,
                    "*{}*: {}, at offset {offset}\n{}",
                    escape(&field.name),
                    escape(&type_text(&field.ty)),
                    indented(&field.doc)
                );
                offset += field_size;
            }
        }
        _ => {}
    }
}

fn module_page(abi: &Abi, module: &Module) -> String {
    let name = page_name(&module.name);
    let mut out = String::new();
    header(&mut out, &name, &module.path);
    let _ = writeln!(
        out,
        "# NAME\n\n{} - {}\n",
        escape(&name),
        escape(&lower_first(&summary(&module.doc)))
    );
    let _ = writeln!(out, "# SYNOPSIS\n\n```\n#include <radix/{}.h>\n```\n", module.name);
    let _ = writeln!(out, "# DESCRIPTION\n\n{}", paragraphs(&module.doc));

    for item in &module.items {
        let ItemKind::Interface { id, version, kind, methods } = &item.kind else { continue };
        let _ = writeln!(out, "# INTERFACE {}\n\n{}", escape(&item.name), paragraphs(&item.doc));
        let _ = writeln!(
            out,
            "Interface number {id:#06x}, version {version}{}.\n",
            kind.as_ref().map_or_default(|k| format!(", answered by *{}* objects", escape(k)))
        );
        if methods.is_empty() {
            out.push_str("It has no methods of its own.\n\n");
        }
        for method in methods {
            let function = format!("radix_{}_{}", item.name, method.name);
            let _ = writeln!(out, "## {}\n", escape(&method.name));
            let _ = writeln!(
                out,
                "Label {:#010x}: {} -> {}\n",
                (id << 16) | method.number,
                escape(&signature(&method.args)),
                escape(&signature(&method.results))
            );
            let _ = writeln!(out, "{}", paragraphs(&method.doc));
            let _ = writeln!(out, "```\n{}\n```\n", c_signature(abi, method, &function, true));
            out.push_str("Errors:\n\n");
            errors_section(&mut out, abi, &method.raises);
            out.push('\n');
        }
    }

    let types: Vec<&Item> = module
        .items
        .iter()
        .filter(|item| {
            matches!(
                item.kind,
                ItemKind::Enum { .. } | ItemKind::Flags { .. } | ItemKind::Struct { .. }
            )
        })
        .collect();
    if !types.is_empty() {
        out.push_str("# TYPES\n\n");
        for item in types {
            type_section(&mut out, abi, item);
        }
    }

    for item in &module.items {
        let ItemKind::Errors { domain, errors } = &item.kind else { continue };
        let _ = writeln!(
            out,
            "# ERRORS ({}, domain {domain})\n\n{}",
            escape(&item.name),
            paragraphs(&item.doc)
        );
        out.push_str("[[ *Code*\n:< *Name*\n:< *errno*\n:< *Meaning*\n");
        for error in errors {
            let _ = writeln!(
                out,
                "|  {}\n:  {}\n:  {}\n:  {}",
                error.value,
                escape(&error.name),
                error.errno.as_deref().unwrap_or("?"),
                escape(&summary(&error.doc))
            );
        }
        out.push('\n');
    }

    let consts: Vec<&Item> =
        module.items.iter().filter(|item| matches!(item.kind, ItemKind::Const { .. })).collect();
    if !consts.is_empty() {
        out.push_str("# CONSTANTS\n\n");
        for item in consts {
            if let ItemKind::Const { ty, value } = &item.kind {
                let _ = writeln!(
                    out,
                    "*{}* = {value:#x} ({})\n{}",
                    escape(&item.name),
                    ty.name(),
                    indented(&item.doc)
                );
            }
        }
    }
    out.push_str("# SEE ALSO\n\n*radix-ipc*(7), *radix-capabilities*(7), *radix-errors*(2), *radix_cap_call*(2)\n");
    out
}
