//! The Rust bindings: one module per `.ridl` file, for `#![no_std]`
//! crates, shared by the kernel (which decodes arguments and encodes
//! results) and user programs (which call through [`Syscalls`]-generic
//! wrappers).

use std::fmt::Write;

use crate::check::{METHOD_WORDS, SYSCALL_WORDS};
use crate::{Abi, Call, Dir, Field, Item, ItemKind, Module, Prim, Type, camel};

/// Words Rust reserves that ridl allows as names.
const RUST_ONLY_KEYWORDS: &[&str] = &["yield", "gen"];

fn ident(name: &str) -> String {
    if RUST_ONLY_KEYWORDS.contains(&name) { format!("r#{name}") } else { name.to_string() }
}

const PRELUDE: &str = r#"
/// A system call's status: 0 for success, otherwise an error's domain (bits
/// 16 to 31), code (bits 0 to 15) and detail (bits 32 to 63).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Default)]
pub struct Status(pub u64);

impl Status {
    /// Success.
    pub const OK: Status = Status(0);

    /// An error status.
    pub const fn new(domain: u16, code: u16, detail: u32) -> Status {
        Status(((detail as u64) << 32) | ((domain as u64) << 16) | code as u64)
    }

    /// Whether it is success.
    pub const fn is_ok(self) -> bool {
        self.0 == 0
    }

    /// The error's domain.
    pub const fn domain(self) -> u16 {
        (self.0 >> 16) as u16
    }

    /// The error's code within its domain.
    pub const fn code(self) -> u16 {
        self.0 as u16
    }

    /// The error's detail.
    pub const fn detail(self) -> u32 {
        (self.0 >> 32) as u32
    }
}

/// How a program enters the kernel: the `syscall` instruction in user
/// programs, a mock in tests.
pub trait Syscalls {
    /// Makes system call `number` with `args` in the ten argument
    /// registers, and returns the status and the ten result registers.
    fn syscall(&self, number: u64, args: [u64; 10]) -> (u64, [u64; 10]);
}

/// A buffer in the caller's memory: its address and length.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Default)]
pub struct UserBuffer {
    /// The address of its first byte.
    pub address: u64,
    /// Its length in bytes.
    pub len: u64,
}

impl UserBuffer {
    /// The buffer `bytes` occupies, for the kernel to read.
    pub fn of(bytes: &[u8]) -> UserBuffer {
        UserBuffer { address: bytes.as_ptr() as u64, len: bytes.len() as u64 }
    }

    /// The buffer `bytes` occupies, for the kernel to write.
    pub fn of_mut(bytes: &mut [u8]) -> UserBuffer {
        UserBuffer { address: bytes.as_mut_ptr() as u64, len: bytes.len() as u64 }
    }
}

/// The position of an argument or result that could not be decoded,
/// counting from 0.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Invalid(pub u32);

#[inline]
#[allow(dead_code)]
fn word_u32(word: u64, at: u32) -> Result<u32, Invalid> {
    u32::try_from(word).map_err(|_| Invalid(at))
}

#[inline]
#[allow(dead_code)]
fn word_i32(word: u64, at: u32) -> Result<i32, Invalid> {
    i32::try_from(word as i64).map_err(|_| Invalid(at))
}

#[inline]
#[allow(dead_code)]
fn word_bool(word: u64, at: u32) -> Result<bool, Invalid> {
    match word {
        0 => Ok(false),
        1 => Ok(true),
        _ => Err(Invalid(at)),
    }
}

#[inline]
#[allow(dead_code)]
fn word_array<const N: usize>(words: &[u64], from: usize) -> [u64; N] {
    let mut array = [0; N];
    array.copy_from_slice(&words[from..from + N]);
    array
}
"#;

/// Generates the Rust bindings for `abi`, as one source file.
pub fn rust(abi: &Abi) -> String {
    let mut out = String::new();
    out.push_str("// Generated by ridlc from abi/*.ridl. Do not edit.\n");
    out.push_str(PRELUDE);
    if abi.error("invalid_argument").is_some() {
        let set = error_set_of(abi, "invalid_argument");
        let _ = write!(
            out,
            "\nimpl From<Invalid> for Status {{\n    fn from(invalid: Invalid) -> Status {{\n        \
             errors::{set}::InvalidArgument.status(invalid.0)\n    }}\n}}\n"
        );
    }
    for module in &abi.modules {
        out.push('\n');
        let _ = writeln!(out, "pub mod {} {{", module.name);
        doc_lines(&mut out, "//!", &module.doc, 4);
        out.push_str("\n    #[allow(unused_imports)]\n    use super::*;\n");
        for item in &module.items {
            out.push('\n');
            item_code(&mut out, abi, module, item);
        }
        out.push_str("}\n");
    }
    out
}

fn error_set_of(abi: &Abi, error: &str) -> String {
    abi.error_sets()
        .into_iter()
        .find(|(_, item)| match &item.kind {
            ItemKind::Errors { errors, .. } => errors.iter().any(|e| e.name == error),
            _ => false,
        })
        .map(|(_, item)| camel(&item.name))
        .unwrap_or_default()
}

/// Writes documentation lines with `marker` (`///` or `//!`), indented.
fn doc_lines(out: &mut String, marker: &str, doc: &[String], indent: usize) {
    let pad = " ".repeat(indent);
    for line in doc {
        if line.is_empty() {
            let _ = writeln!(out, "{pad}{marker}");
        } else {
            let _ = writeln!(out, "{pad}{marker} {line}");
        }
    }
}

fn doc(out: &mut String, doc: &[String], indent: usize) {
    doc_lines(out, "///", doc, indent);
}

/// The Rust type of `ty`, as seen from `module`.
fn rust_type(abi: &Abi, module: &Module, ty: &Type) -> String {
    match ty {
        Type::Prim(prim) => prim.name().to_string(),
        Type::Slot => "u32".into(),
        Type::Addr => "u64".into(),
        Type::Named(name) => qualified(abi, module, name),
        Type::Array(inner, len) => format!("[{}; {len}]", rust_type(abi, module, inner)),
        Type::Bytes(_) => "UserBuffer".into(),
    }
}

fn qualified(abi: &Abi, module: &Module, name: &str) -> String {
    match abi.find(name) {
        Some((owner, _)) if owner.name != module.name => format!("{}::{name}", owner.name),
        _ => name.to_string(),
    }
}

fn item_code(out: &mut String, abi: &Abi, module: &Module, item: &Item) {
    match &item.kind {
        ItemKind::Const { ty, value } => {
            doc(out, &item.doc, 4);
            let _ = writeln!(out, "    pub const {}: {} = {value:#x};", item.name, ty.name());
        }
        ItemKind::Enum { repr, variants } => {
            let name = &item.name;
            let repr = repr.name();
            doc(out, &item.doc, 4);
            let _ = writeln!(out, "    #[repr({repr})]");
            out.push_str("    #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\n");
            let _ = writeln!(out, "    pub enum {name} {{");
            for variant in variants {
                doc(out, &variant.doc, 8);
                let _ = writeln!(out, "        {} = {},", camel(&variant.name), variant.value);
            }
            out.push_str("    }\n\n");
            let _ = writeln!(out, "    impl {name} {{");
            let _ = writeln!(out, "        /// Every variant, in the order of their numbers.");
            let _ = writeln!(out, "        pub const ALL: [{name}; {}] = [", variants.len());
            let mut sorted: Vec<_> = variants.iter().collect();
            sorted.sort_by_key(|v| v.value);
            for variant in &sorted {
                let _ = writeln!(out, "            {name}::{},", camel(&variant.name));
            }
            out.push_str("        ];\n\n");
            let _ = writeln!(out, "        /// Its number.");
            let _ = writeln!(
                out,
                "        pub const fn raw(self) -> {repr} {{\n            self as {repr}\n        }}\n"
            );
            let _ = writeln!(out, "        /// The variant numbered `raw`.");
            let _ =
                writeln!(out, "        pub const fn from_raw(raw: {repr}) -> Option<{name}> {{");
            out.push_str("            match raw {\n");
            for variant in variants {
                let _ = writeln!(
                    out,
                    "                {} => Some({name}::{}),",
                    variant.value,
                    camel(&variant.name)
                );
            }
            out.push_str("                _ => None,\n            }\n        }\n\n");
            let _ = writeln!(out, "        /// Its name in the interface definition.");
            out.push_str(
                "        pub const fn name(self) -> &'static str {\n            match self {\n",
            );
            for variant in variants {
                let _ = writeln!(
                    out,
                    "                {name}::{} => \"{}\",",
                    camel(&variant.name),
                    variant.name
                );
            }
            out.push_str("            }\n        }\n    }\n");
        }
        ItemKind::Flags { repr, bits } => {
            let name = &item.name;
            let repr = repr.name();
            doc(out, &item.doc, 4);
            out.push_str("    #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Default)]\n");
            let _ = writeln!(out, "    pub struct {name}(pub {repr});\n");
            let _ = writeln!(out, "    impl {name} {{");
            let _ = writeln!(out, "        /// No flags.");
            let _ = writeln!(out, "        pub const NONE: {name} = {name}(0);");
            for bit in bits {
                doc(out, &bit.doc, 8);
                let value =
                    if bit.value == 0 { "1".to_string() } else { format!("1 << {}", bit.value) };
                let _ = writeln!(
                    out,
                    "        pub const {}: {name} = {name}({value});",
                    bit.name.to_uppercase()
                );
            }
            let all = bits.iter().fold(0u64, |all, bit| all | (1 << bit.value));
            let _ = writeln!(out, "        /// Every flag.");
            let _ = writeln!(out, "        pub const ALL: {name} = {name}({all:#x});");
            let _ = writeln!(out, "        /// Each flag and its name.");
            let _ = writeln!(
                out,
                "        pub const NAMES: [({name}, &'static str); {}] = [",
                bits.len()
            );
            for bit in bits {
                let _ = writeln!(
                    out,
                    "            ({name}::{}, \"{}\"),",
                    bit.name.to_uppercase(),
                    bit.name
                );
            }
            out.push_str("        ];\n\n");
            let _ = writeln!(out, "        /// The flags' bits.");
            let _ = writeln!(
                out,
                "        pub const fn bits(self) -> {repr} {{\n            self.0\n        }}\n"
            );
            let _ = writeln!(out, "        /// The flags with these bits, if every bit is a flag.");
            let _ =
                writeln!(out, "        pub const fn from_bits(bits: {repr}) -> Option<{name}> {{");
            let _ = writeln!(
                out,
                "            if bits & !{name}::ALL.0 == 0 {{ Some({name}(bits)) }} else {{ None }}\n        }}\n"
            );
            let _ = writeln!(out, "        /// Whether every flag of `other` is set.");
            let _ = writeln!(
                out,
                "        pub const fn contains(self, other: {name}) -> bool {{\n            self.0 & other.0 == other.0\n        }}\n"
            );
            let _ = writeln!(out, "        /// The flags of both.");
            let _ = writeln!(
                out,
                "        pub const fn union(self, other: {name}) -> {name} {{\n            {name}(self.0 | other.0)\n        }}\n"
            );
            let _ = writeln!(out, "        /// The flags both have.");
            let _ = writeln!(
                out,
                "        pub const fn intersection(self, other: {name}) -> {name} {{\n            {name}(self.0 & other.0)\n        }}\n"
            );
            let _ = writeln!(out, "        /// Whether no flag is set.");
            let _ = writeln!(
                out,
                "        pub const fn is_empty(self) -> bool {{\n            self.0 == 0\n        }}\n    }}"
            );
        }
        ItemKind::Errors { domain, errors } => {
            let name = camel(&item.name);
            doc(out, &item.doc, 4);
            out.push_str(
                "    #[repr(u16)]\n    #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\n",
            );
            let _ = writeln!(out, "    pub enum {name} {{");
            for error in errors {
                doc(out, &error.doc, 8);
                let _ = writeln!(out, "        {} = {},", camel(&error.name), error.value);
            }
            out.push_str("    }\n\n");
            let _ = writeln!(out, "    impl {name} {{");
            let _ = writeln!(out, "        /// The errors' domain.");
            let _ = writeln!(out, "        pub const DOMAIN: u16 = {domain};\n");
            let _ = writeln!(out, "        /// Every error.");
            let _ = writeln!(out, "        pub const ALL: [{name}; {}] = [", errors.len());
            for error in errors {
                let _ = writeln!(out, "            {name}::{},", camel(&error.name));
            }
            out.push_str("        ];\n\n");
            let _ = writeln!(out, "        /// Its code.");
            out.push_str(
                "        pub const fn code(self) -> u16 {\n            self as u16\n        }\n\n",
            );
            let _ = writeln!(out, "        /// The error with this code.");
            let _ = writeln!(
                out,
                "        pub const fn from_code(code: u16) -> Option<{name}> {{\n            match code {{"
            );
            for error in errors {
                let _ = writeln!(
                    out,
                    "                {} => Some({name}::{}),",
                    error.value,
                    camel(&error.name)
                );
            }
            out.push_str("                _ => None,\n            }\n        }\n\n");
            let _ = writeln!(out, "        /// The status with this error and `detail`.");
            let _ = writeln!(
                out,
                "        pub const fn status(self, detail: u32) -> Status {{\n            Status::new(Self::DOMAIN, self as u16, detail)\n        }}\n"
            );
            let _ = writeln!(out, "        /// The error a status holds, if it is one of these.");
            let _ = writeln!(
                out,
                "        pub const fn from_status(status: Status) -> Option<{name}> {{"
            );
            let _ = writeln!(
                out,
                "            if status.domain() == Self::DOMAIN {{ Self::from_code(status.code()) }} else {{ None }}\n        }}\n"
            );
            let _ = writeln!(out, "        /// The POSIX errno it maps to.");
            out.push_str("        pub const fn errno(self) -> i32 {\n            match self {\n");
            for error in errors {
                let errno = error.errno.as_deref().and_then(crate::errno).unwrap_or(0);
                let _ = writeln!(out, "                {name}::{} => {errno},", camel(&error.name));
            }
            out.push_str("            }\n        }\n\n");
            let _ = writeln!(out, "        /// Its name in the interface definition.");
            out.push_str(
                "        pub const fn name(self) -> &'static str {\n            match self {\n",
            );
            for error in errors {
                let _ = writeln!(
                    out,
                    "                {name}::{} => \"{}\",",
                    camel(&error.name),
                    error.name
                );
            }
            out.push_str("            }\n        }\n\n");
            let _ = writeln!(out, "        /// What it means, in a sentence.");
            out.push_str("        pub const fn description(self) -> &'static str {\n            match self {\n");
            for error in errors {
                let summary = crate::summary(&error.doc).replace('\\', "\\\\").replace('"', "\\\"");
                let _ = writeln!(
                    out,
                    "                {name}::{} => \"{summary}\",",
                    camel(&error.name)
                );
            }
            out.push_str("            }\n        }\n    }\n\n");
            let _ = writeln!(out, "    impl core::fmt::Display for {name} {{");
            out.push_str(
                "        fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {\n",
            );
            out.push_str("            f.write_str(self.description())\n        }\n    }\n");
        }
        ItemKind::Struct { fields } => {
            let name = &item.name;
            doc(out, &item.doc, 4);
            out.push_str(
                "    #[repr(C)]\n    #[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]\n",
            );
            let _ = writeln!(out, "    pub struct {name} {{");
            for field in fields {
                doc(out, &field.doc, 8);
                let _ = writeln!(
                    out,
                    "        pub {}: {},",
                    field.name,
                    rust_type(abi, module, &field.ty)
                );
            }
            out.push_str("    }\n\n");
            let (size, _) = abi.layout(&Type::Named(name.clone())).unwrap_or((0, 1));
            let _ = writeln!(out, "    impl {name} {{");
            let _ = writeln!(out, "        /// Its size in bytes.");
            let _ = writeln!(out, "        pub const SIZE: usize = {size};");
            let mut offset: usize = 0;
            for field in fields {
                let (field_size, align) = abi.layout(&field.ty).unwrap_or((0, 1));
                offset = offset.next_multiple_of(align);
                let _ = writeln!(out, "        /// The offset of `{}`.", field.name);
                let _ = writeln!(
                    out,
                    "        pub const OFFSET_{}: usize = {offset};",
                    field.name.to_uppercase()
                );
                offset += field_size;
            }
            out.push_str("    }\n\n");
            let _ = writeln!(
                out,
                "    const _: () = assert!(core::mem::size_of::<{name}>() == {name}::SIZE);"
            );
            for field in fields {
                let _ = writeln!(
                    out,
                    "    const _: () = assert!(core::mem::offset_of!({name}, {}) == {name}::OFFSET_{});",
                    field.name,
                    field.name.to_uppercase()
                );
            }
        }
        ItemKind::Syscall(call) => {
            let constant = call.name.to_uppercase();
            let _ = writeln!(out, "    /// The number of the `{}` system call.", call.name);
            let _ = writeln!(out, "    pub const {constant}: u64 = {};\n", call.number);
            call_code(out, abi, module, call, &CallShape::Syscall);
            if is_last_syscall(module, item) {
                syscall_names(out, abi);
            }
        }
        ItemKind::Interface { id, version, kind, methods } => {
            let nested = item.name != module.name;
            let indent = if nested { 8 } else { 4 };
            let pad = " ".repeat(indent);
            if nested {
                doc(out, &item.doc, 4);
                let _ = writeln!(out, "    pub mod {} {{", item.name);
                out.push_str("        #[allow(unused_imports)]\n        use super::*;\n\n");
            } else {
                doc(out, &item.doc, 4);
                let _ = writeln!(out, "    pub const INTERFACE: u16 = {id:#06x};");
                out.push('\n');
            }
            if nested {
                let _ = writeln!(
                    out,
                    "{pad}/// The interface's number: the high half of its methods' labels."
                );
                let _ = writeln!(out, "{pad}pub const INTERFACE: u16 = {id:#06x};");
            }
            let _ = writeln!(out, "{pad}/// The interface's version.");
            let _ = writeln!(out, "{pad}pub const VERSION: u32 = {version};");
            if let Some(kind) = kind {
                let path = qualified(abi, module, "ObjectKind");
                let _ = writeln!(out, "{pad}/// The kind of object that answers it.");
                let _ = writeln!(out, "{pad}pub const KIND: {path} = {path}::{};", camel(kind));
            }
            for method in methods {
                out.push('\n');
                let label = (id << 16) | method.number;
                let _ = writeln!(out, "{pad}/// The label of the `{}` method.", method.name);
                let _ = writeln!(
                    out,
                    "{pad}pub const {}: u32 = {label:#010x};\n",
                    method.name.to_uppercase()
                );
                let mut text = String::new();
                call_code(&mut text, abi, module, method, &CallShape::Method { label });
                if nested {
                    for line in text.lines() {
                        if line.is_empty() {
                            out.push('\n');
                        } else {
                            let _ = writeln!(out, "    {line}");
                        }
                    }
                } else {
                    out.push_str(&text);
                }
            }
            if nested {
                out.push_str("    }\n");
            }
        }
    }
}

fn is_last_syscall(module: &Module, item: &Item) -> bool {
    let last = module.items.iter().rev().find(|i| matches!(i.kind, ItemKind::Syscall(_)));
    last.is_some_and(|last| std::ptr::eq(last, item))
}

fn syscall_names(out: &mut String, abi: &Abi) {
    out.push_str("\n    /// The name of the system call numbered `number`.\n");
    out.push_str(
        "    pub const fn name(number: u64) -> Option<&'static str> {\n        match number {\n",
    );
    for (_, call) in abi.syscalls() {
        let _ = writeln!(out, "            {} => Some(\"{}\"),", call.number, call.name);
    }
    out.push_str("            _ => None,\n        }\n    }\n");
}

enum CallShape {
    Syscall,
    Method { label: u64 },
}

impl CallShape {
    fn words(&self) -> usize {
        match self {
            CallShape::Syscall => SYSCALL_WORDS,
            CallShape::Method { .. } => METHOD_WORDS,
        }
    }
}

/// Encodes field `field` of `value` into `words` from word `at`.
fn encode_field(out: &mut String, abi: &Abi, field: &Field, value: &str, at: usize) {
    let name = format!("{value}.{}", field.name);
    let line = match &field.ty {
        Type::Prim(Prim::U64) | Type::Addr => format!("words[{at}] = {name};"),
        Type::Prim(Prim::I64) => format!("words[{at}] = {name} as u64;"),
        Type::Prim(Prim::I32) => format!("words[{at}] = {name} as i64 as u64;"),
        Type::Prim(_) | Type::Slot => format!("words[{at}] = {name} as u64;"),
        Type::Named(other) => match abi.find(other).map(|(_, item)| &item.kind) {
            Some(ItemKind::Flags { repr: Prim::U64, .. }) => format!("words[{at}] = {name}.bits();"),
            Some(ItemKind::Flags { .. }) => format!("words[{at}] = {name}.bits() as u64;"),
            Some(ItemKind::Enum { repr: Prim::U64, .. }) => format!("words[{at}] = {name}.raw();"),
            _ => format!("words[{at}] = {name}.raw() as u64;"),
        },
        Type::Array(_, len) => format!("words[{at}..{}].copy_from_slice(&{name});", at + len),
        Type::Bytes(_) => {
            format!("words[{at}] = {name}.address;\n            words[{}] = {name}.len;", at + 1)
        }
    };
    let _ = writeln!(out, "            {line}");
}

/// The expression decoding field `field` (parameter `position`) from
/// `words` at word `at`.
fn decode_field(abi: &Abi, module: &Module, field: &Field, position: usize, at: usize) -> String {
    let p = position;
    match &field.ty {
        Type::Prim(Prim::U64) | Type::Addr => format!("words[{at}]"),
        Type::Prim(Prim::I64) => format!("words[{at}] as i64"),
        Type::Prim(Prim::U32) | Type::Slot => format!("word_u32(words[{at}], {p})?"),
        Type::Prim(Prim::I32) => format!("word_i32(words[{at}], {p})?"),
        Type::Prim(Prim::Bool) => format!("word_bool(words[{at}], {p})?"),
        Type::Prim(prim) => {
            format!("{}::try_from(words[{at}]).map_err(|_| Invalid({p}))?", prim.name())
        }
        Type::Named(other) => {
            let path = qualified(abi, module, other);
            match abi.find(other).map(|(_, item)| &item.kind) {
                Some(ItemKind::Flags { repr, .. }) | Some(ItemKind::Enum { repr, .. }) => {
                    let method = if matches!(
                        abi.find(other).map(|(_, i)| &i.kind),
                        Some(ItemKind::Flags { .. })
                    ) {
                        "from_bits"
                    } else {
                        "from_raw"
                    };
                    if *repr == Prim::U64 {
                        format!("{path}::{method}(words[{at}]).ok_or(Invalid({p}))?")
                    } else {
                        format!(
                            "{}::try_from(words[{at}]).ok().and_then({path}::{method}).ok_or(Invalid({p}))?",
                            repr.name()
                        )
                    }
                }
                _ => format!("compile_error!(\"cannot decode {other}\")"),
            }
        }
        Type::Array(_, len) => format!("word_array::<{len}>(words, {at})"),
        Type::Bytes(_) => format!("UserBuffer {{ address: words[{at}], len: words[{}] }}", at + 1),
    }
}

/// Writes a parameter structure (`Args` or `Results`) with its encoder
/// and decoder.
#[allow(clippy::too_many_arguments)]
fn params_struct(
    out: &mut String,
    abi: &Abi,
    module: &Module,
    name: &str,
    what: &str,
    call: &str,
    fields: &[Field],
    width: usize,
) {
    let _ = writeln!(out, "    /// The {what} of `{call}`.");
    out.push_str("    #[derive(Clone, Copy, Debug, PartialEq, Eq)]\n");
    if fields.is_empty() {
        let _ = writeln!(out, "    pub struct {name} {{}}\n");
    } else {
        let _ = writeln!(out, "    pub struct {name} {{");
        for field in fields {
            let _ = writeln!(out, "        /// `{}`.", field.name);
            let _ =
                writeln!(out, "        pub {}: {},", field.name, rust_type(abi, module, &field.ty));
        }
        out.push_str("    }\n\n");
    }
    let total: usize = fields.iter().map(|field| abi.words(&field.ty)).sum();
    let _ = writeln!(out, "    impl {name} {{");
    let _ = writeln!(out, "        /// How many words they take.");
    let _ = writeln!(out, "        pub const WORDS: usize = {total};\n");
    let _ = writeln!(out, "        /// Packs them into words.");
    let _ = writeln!(out, "        pub fn encode(&self) -> [u64; {width}] {{");
    if fields.is_empty() {
        let _ = writeln!(out, "            [0; {width}]\n        }}\n");
    } else {
        let _ = writeln!(out, "            let mut words = [0u64; {width}];");
        let mut at = 0;
        for field in fields {
            encode_field(out, abi, field, "self", at);
            at += abi.words(&field.ty);
        }
        out.push_str("            words\n        }\n\n");
    }
    let _ = writeln!(out, "        /// Unpacks them from words, checking each.");
    let words_param = if fields.is_empty() { "_words" } else { "words" };
    let _ = writeln!(
        out,
        "        pub fn decode({words_param}: &[u64; {width}]) -> Result<{name}, Invalid> {{"
    );
    if fields.is_empty() {
        let _ = writeln!(out, "            Ok({name} {{}})\n        }}\n    }}\n");
        return;
    }
    let _ = writeln!(out, "            Ok({name} {{");
    let mut at = 0;
    for (position, field) in fields.iter().enumerate() {
        let _ = writeln!(
            out,
            "                {}: {},",
            field.name,
            decode_field(abi, module, field, position, at)
        );
        at += abi.words(&field.ty);
    }
    out.push_str("            })\n        }\n    }\n\n");
}

/// The wrapper's parameter type for a field.
fn wrapper_type(abi: &Abi, module: &Module, field: &Field) -> String {
    match &field.ty {
        Type::Bytes(Dir::In) => "&[u8]".into(),
        Type::Bytes(Dir::Out) => "&mut [u8]".into(),
        other => rust_type(abi, module, other),
    }
}

fn wrapper_value(field: &Field) -> String {
    match &field.ty {
        Type::Bytes(Dir::In) => format!("{}: UserBuffer::of({})", field.name, field.name),
        Type::Bytes(Dir::Out) => format!("{}: UserBuffer::of_mut({})", field.name, field.name),
        _ => field.name.clone(),
    }
}

fn call_code(out: &mut String, abi: &Abi, module: &Module, call: &Call, shape: &CallShape) {
    let base = camel(&call.name);
    let width = shape.words();
    params_struct(
        out,
        abi,
        module,
        &format!("{base}Args"),
        "arguments",
        &call.name,
        &call.args,
        width,
    );
    params_struct(
        out,
        abi,
        module,
        &format!("{base}Results"),
        "results",
        &call.name,
        &call.results,
        width,
    );

    doc(out, &call.doc, 4);
    let mut params = vec!["sys: &S".to_string()];
    if let CallShape::Method { .. } = shape {
        params.push("cap: u32".into());
    }
    for field in &call.args {
        params.push(format!("{}: {}", field.name, wrapper_type(abi, module, field)));
    }
    let returns = if call.results.is_empty() { "()".to_string() } else { format!("{base}Results") };
    let _ = writeln!(
        out,
        "    pub fn {}<S: Syscalls + ?Sized>({}) -> Result<{returns}, Status> {{",
        ident(&call.name),
        params.join(", ")
    );
    let values: Vec<String> = call.args.iter().map(wrapper_value).collect();
    let _ = writeln!(out, "        let words = {base}Args {{ {} }}.encode();", values.join(", "));
    let syscalls_path = if module.name == "syscalls" { String::new() } else { "syscalls::".into() };
    match shape {
        CallShape::Syscall => {
            let _ = writeln!(
                out,
                "        let (status, out) = sys.syscall({}, words);",
                call.name.to_uppercase()
            );
        }
        CallShape::Method { label } => {
            let _ = writeln!(
                out,
                "        let info = {label:#x} | (({base}Args::WORDS as u64) << {});",
                32
            );
            let _ = writeln!(
                out,
                "        let (status, out) = sys.syscall(\n            {syscalls_path}CAP_CALL,\n            \
                 [cap as u64, info, words[0], words[1], words[2], words[3], words[4], words[5], words[6], words[7]],\n        );"
            );
        }
    }
    out.push_str("        if status != 0 {\n            return Err(Status(status));\n        }\n");
    match shape {
        CallShape::Syscall => {
            if call.results.is_empty() {
                out.push_str("        let _ = out;\n        Ok(())\n");
            } else {
                let _ = writeln!(out, "        Ok({base}Results::decode(&out)?)");
            }
        }
        CallShape::Method { .. } => {
            if call.results.is_empty() {
                out.push_str("        let _ = out;\n        Ok(())\n");
            } else {
                let _ =
                    writeln!(out, "        Ok({base}Results::decode(&word_array::<8>(&out, 2))?)");
            }
        }
    }
    out.push_str("    }\n");
}
