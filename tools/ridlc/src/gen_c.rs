//! The C headers: `radix/abi.h` with the system call stub, one header per
//! module, and `radix/radix.h` that includes them all. They are C11 and
//! need only `<stdint.h>`, `<stddef.h>` and `<stdbool.h>`.

use std::collections::BTreeSet;
use std::fmt::Write;

use crate::{Abi, Call, Dir, Field, ItemKind, Module, Prim, Type, snake};

/// The license line of every generated header but `abi.h`, which has its
/// own. The tag is split so that REUSE does not read it as this file's.
const LICENSE_LINE: &str = concat!("/* SPDX-", "License-Identifier: Apache-2.0 OR MIT */\n\n");

const ABI_H: &str = r#"/* Generated by ridlc from the files in abi/. Do not edit. */
/* SPDX-License-Identifier: Apache-2.0 OR MIT */

/*
 * The Radix system call interface: the status word and the system call
 * stub every other header uses.
 */

#ifndef RADIX_ABI_H
#define RADIX_ABI_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

/* A status: 0 for success, else the error's domain, code and detail. */
#define RADIX_STATUS_DOMAIN(status) ((uint16_t)((status) >> 16))
#define RADIX_STATUS_CODE(status) ((uint16_t)(status))
#define RADIX_STATUS_DETAIL(status) ((uint32_t)((status) >> 32))

/*
 * A function that makes system calls as `radix_syscall` does. Each call's
 * function has a form ending in `_with` that takes one: a C library's
 * own, which can make a call a cancellation point, for example.
 */
typedef uint64_t radix_syscall_fn(uint64_t number, const uint64_t in[10], uint64_t out[10]);

/*
 * Makes system call `number` with `in` in the ten argument registers,
 * stores the ten result registers in `out`, and returns the status.
 */
static inline uint64_t radix_syscall(uint64_t number, const uint64_t in[10], uint64_t out[10])
{
#if defined(__x86_64__)
    register uint64_t rax __asm__("rax") = number;
    register uint64_t rdi __asm__("rdi") = in[0];
    register uint64_t rsi __asm__("rsi") = in[1];
    register uint64_t rdx __asm__("rdx") = in[2];
    register uint64_t r10 __asm__("r10") = in[3];
    register uint64_t r8 __asm__("r8") = in[4];
    register uint64_t r9 __asm__("r9") = in[5];
    register uint64_t r12 __asm__("r12") = in[6];
    register uint64_t r13 __asm__("r13") = in[7];
    register uint64_t r14 __asm__("r14") = in[8];
    register uint64_t r15 __asm__("r15") = in[9];
    __asm__ __volatile__("syscall"
                         : "+r"(rax), "+r"(rdi), "+r"(rsi), "+r"(rdx), "+r"(r10), "+r"(r8),
                           "+r"(r9), "+r"(r12), "+r"(r13), "+r"(r14), "+r"(r15)
                         :
                         : "rcx", "r11", "memory");
    out[0] = rdi;
    out[1] = rsi;
    out[2] = rdx;
    out[3] = r10;
    out[4] = r8;
    out[5] = r9;
    out[6] = r12;
    out[7] = r13;
    out[8] = r14;
    out[9] = r15;
    return rax;
#else
#error "radix/abi.h has no system call stub for this architecture yet"
#endif
}

#endif
"#;

/// Generates the C headers for `abi`, as (path under `include/`, text).
pub fn c_headers(abi: &Abi) -> Vec<(String, String)> {
    let mut headers = vec![("radix/abi.h".to_string(), ABI_H.to_string())];
    let mut all = String::new();
    all.push_str("/* Generated by ridlc from the files in abi/. Do not edit. */\n");
    all.push_str(LICENSE_LINE);
    all.push_str(
        "/* Every Radix interface. */\n\n#ifndef RADIX_RADIX_H\n#define RADIX_RADIX_H\n\n",
    );
    all.push_str("#include <radix/abi.h>\n");
    for module in &abi.modules {
        headers.push((format!("radix/{}.h", module.name), header(abi, module)));
        let _ = writeln!(all, "#include <radix/{}.h>", module.name);
    }
    all.push_str("\n#endif\n");
    headers.push(("radix/radix.h".to_string(), all));
    headers
}

fn comment(out: &mut String, doc: &[String], indent: &str) {
    if doc.is_empty() {
        return;
    }
    let _ = writeln!(out, "{indent}/*");
    for line in doc {
        let line = line.replace("*/", "* /");
        if line.is_empty() {
            let _ = writeln!(out, "{indent} *");
        } else {
            let _ = writeln!(out, "{indent} * {line}");
        }
    }
    let _ = writeln!(out, "{indent} */");
}

fn upper(name: &str) -> String {
    snake(name).to_uppercase()
}

pub(crate) fn prim(prim: Prim) -> &'static str {
    match prim {
        Prim::U8 => "uint8_t",
        Prim::U16 => "uint16_t",
        Prim::U32 => "uint32_t",
        Prim::U64 => "uint64_t",
        Prim::I32 => "int32_t",
        Prim::I64 => "int64_t",
        Prim::Bool => "bool",
    }
}

fn literal(ty: Prim, value: u64) -> String {
    match ty {
        Prim::U64 | Prim::I64 => format!("UINT64_C({value:#x})"),
        _ => format!("UINT32_C({value:#x})"),
    }
}

/// The C type of a scalar `ty`.
fn c_type(abi: &Abi, ty: &Type) -> String {
    match ty {
        Type::Prim(p) => prim(*p).to_string(),
        Type::Slot => "uint32_t".into(),
        Type::Addr => "uint64_t".into(),
        Type::Named(name) => match abi.find(name).map(|(_, item)| &item.kind) {
            Some(ItemKind::Enum { .. }) => format!("enum radix_{}", snake(name)),
            Some(ItemKind::Flags { repr, .. }) => prim(*repr).to_string(),
            _ => format!("struct radix_{}", snake(name)),
        },
        Type::Array(inner, _) => c_type(abi, inner),
        Type::Bytes(_) => "uint64_t".into(),
    }
}

/// A declaration of `name` with type `ty`, arrays included.
fn declaration(abi: &Abi, ty: &Type, name: &str) -> String {
    match ty {
        Type::Array(inner, len) => format!("{} {name}[{len}]", c_type(abi, inner)),
        _ => format!("{} {name}", c_type(abi, ty)),
    }
}

/// The modules whose types `module` refers to.
fn dependencies(abi: &Abi, module: &Module) -> BTreeSet<String> {
    let mut deps = BTreeSet::new();
    let mut needs_syscalls = false;
    let mut add = |ty: &Type| {
        let mut ty = ty;
        while let Type::Array(inner, _) = ty {
            ty = inner;
        }
        if let Type::Named(name) = ty
            && let Some((owner, _)) = abi.find(name)
            && owner.name != module.name
        {
            deps.insert(owner.name.clone());
        }
    };
    for item in &module.items {
        match &item.kind {
            ItemKind::Struct { fields } => fields.iter().for_each(|f| add(&f.ty)),
            ItemKind::Syscall(call) => {
                call.args.iter().chain(&call.results).for_each(|f| add(&f.ty))
            }
            ItemKind::Interface { kind, methods, .. } => {
                if kind.is_some() {
                    add(&Type::Named("ObjectKind".into()));
                }
                for call in methods {
                    call.args.iter().chain(&call.results).for_each(|f| add(&f.ty));
                }
                if !methods.is_empty() && module.name != "syscalls" {
                    needs_syscalls = true;
                }
            }
            _ => {}
        }
    }
    if needs_syscalls {
        deps.insert("syscalls".into());
    }
    deps
}

fn header(abi: &Abi, module: &Module) -> String {
    let guard = format!("RADIX_{}_H", module.name.to_uppercase());
    let mut out = String::new();
    out.push_str("/* Generated by ridlc from the files in abi/. Do not edit. */\n");
    out.push_str(LICENSE_LINE);
    comment(&mut out, &module.doc, "");
    let _ = writeln!(out, "\n#ifndef {guard}\n#define {guard}\n\n#include <radix/abi.h>");
    for dep in dependencies(abi, module) {
        let _ = writeln!(out, "#include <radix/{dep}.h>");
    }
    let prefix = format!("RADIX_{}", module.name.to_uppercase());
    for item in &module.items {
        out.push('\n');
        match &item.kind {
            ItemKind::Const { ty, value } => {
                comment(&mut out, &item.doc, "");
                let _ = writeln!(out, "#define {prefix}_{} {}", item.name, literal(*ty, *value));
            }
            ItemKind::Enum { variants, .. } => {
                let name = snake(&item.name);
                comment(&mut out, &item.doc, "");
                let _ = writeln!(out, "enum radix_{name} {{");
                for variant in variants {
                    comment(&mut out, &variant.doc, "    ");
                    let _ = writeln!(
                        out,
                        "    RADIX_{}_{} = {},",
                        upper(&item.name),
                        variant.name.to_uppercase(),
                        variant.value
                    );
                }
                out.push_str("};\n");
            }
            ItemKind::Flags { repr, bits } => {
                comment(&mut out, &item.doc, "");
                let _ = writeln!(out, "typedef {} radix_{}_t;", prim(*repr), snake(&item.name));
                for bit in bits {
                    comment(&mut out, &bit.doc, "");
                    let _ = writeln!(
                        out,
                        "#define RADIX_{}_{} ({} << {})",
                        upper(&item.name),
                        bit.name.to_uppercase(),
                        literal(*repr, 1),
                        bit.value
                    );
                }
            }
            ItemKind::Errors { domain, errors } => {
                let set = item.name.to_uppercase();
                comment(&mut out, &item.doc, "");
                let _ = writeln!(out, "#define RADIX_{set}_ERROR_DOMAIN {domain}\n");
                let _ = writeln!(out, "enum radix_{}_error {{", item.name);
                for error in errors {
                    comment(&mut out, &error.doc, "    ");
                    let _ = writeln!(
                        out,
                        "    RADIX_{set}_{} = {},",
                        error.name.to_uppercase(),
                        error.value
                    );
                }
                out.push_str("};\n\n");
                out.push_str("/* The errno a status maps to: 0 for success, EIO (5) for an unknown error. */\n");
                let _ = writeln!(
                    out,
                    "static inline int radix_{}_errno(uint64_t status)\n{{",
                    item.name
                );
                out.push_str("    if (status == 0) {\n        return 0;\n    }\n");
                let _ = writeln!(
                    out,
                    "    if (RADIX_STATUS_DOMAIN(status) != RADIX_{set}_ERROR_DOMAIN) {{\n        return 5;\n    }}"
                );
                out.push_str("    switch (RADIX_STATUS_CODE(status)) {\n");
                for error in errors {
                    let errno = error.errno.as_deref().and_then(crate::errno).unwrap_or(5);
                    let _ = writeln!(
                        out,
                        "    case RADIX_{set}_{}:\n        return {errno};",
                        error.name.to_uppercase()
                    );
                }
                out.push_str("    default:\n        return 5;\n    }\n}\n");
            }
            ItemKind::Struct { fields } => {
                let name = format!("radix_{}", snake(&item.name));
                comment(&mut out, &item.doc, "");
                let _ = writeln!(out, "struct {name} {{");
                for field in fields {
                    comment(&mut out, &field.doc, "    ");
                    let _ = writeln!(out, "    {};", declaration(abi, &field.ty, &field.name));
                }
                out.push_str("};\n\n");
                let (size, _) = abi.layout(&Type::Named(item.name.clone())).unwrap_or((0, 1));
                let _ = writeln!(
                    out,
                    "_Static_assert(sizeof(struct {name}) == {size}, \"struct {name} has the wrong size\");"
                );
                let mut offset: usize = 0;
                for field in fields {
                    let (field_size, align) = abi.layout(&field.ty).unwrap_or((0, 1));
                    offset = offset.next_multiple_of(align);
                    let _ = writeln!(
                        out,
                        "_Static_assert(offsetof(struct {name}, {}) == {offset}, \"{name}.{} is misplaced\");",
                        field.name, field.name
                    );
                    offset += field_size;
                }
            }
            ItemKind::Syscall(call) => {
                let _ = writeln!(out, "/* The number of the {} system call. */", call.name);
                let _ = writeln!(
                    out,
                    "#define RADIX_SYSCALL_{} {}\n",
                    call.name.to_uppercase(),
                    call.number
                );
                call_code(&mut out, abi, call, &format!("radix_{}", call.name), None);
            }
            ItemKind::Interface { id, version, kind, methods } => {
                let iface = item.name.to_uppercase();
                comment(&mut out, &item.doc, "");
                let _ = writeln!(out, "#define RADIX_{iface}_INTERFACE {id:#06x}");
                let _ = writeln!(out, "#define RADIX_{iface}_VERSION {version}");
                if let Some(kind) = kind {
                    let _ = writeln!(
                        out,
                        "#define RADIX_{iface}_KIND RADIX_OBJECT_KIND_{}",
                        kind.to_uppercase()
                    );
                }
                for method in methods {
                    let label = (id << 16) | method.number;
                    out.push('\n');
                    let _ = writeln!(
                        out,
                        "/* The label of the {} method of {}. */",
                        method.name, item.name
                    );
                    let _ = writeln!(
                        out,
                        "#define RADIX_{iface}_{} UINT32_C({label:#010x})\n",
                        method.name.to_uppercase()
                    );
                    call_code(
                        &mut out,
                        abi,
                        method,
                        &format!("radix_{}_{}", item.name, method.name),
                        Some(label),
                    );
                }
            }
        }
    }
    let _ = writeln!(out, "\n#endif");
    out
}

/// The statements packing argument `field` into `words` from `at`.
fn pack(abi: &Abi, field: &Field, at: usize, out: &mut String) {
    let name = &field.name;
    match &field.ty {
        Type::Array(_, len) => {
            let _ = writeln!(
                out,
                "    for (size_t i = 0; i < {len}; i++) {{\n        radix_args_[{at} + i] = {name}[i];\n    }}"
            );
        }
        Type::Bytes(_) => {
            let _ = writeln!(
                out,
                "    radix_args_[{at}] = (uint64_t)(uintptr_t){name};\n    radix_args_[{}] = (uint64_t){name}_len;",
                at + 1
            );
        }
        Type::Prim(Prim::I32 | Prim::I64) => {
            let _ = writeln!(out, "    radix_args_[{at}] = (uint64_t)(int64_t){name};");
        }
        Type::Named(other)
            if matches!(abi.find(other).map(|(_, i)| &i.kind), Some(ItemKind::Enum { .. })) =>
        {
            let _ = writeln!(out, "    radix_args_[{at}] = (uint64_t){name};");
        }
        _ => {
            let _ = writeln!(out, "    radix_args_[{at}] = (uint64_t){name};");
        }
    }
}

/// The statements unpacking result `field` from `out` at `at`.
fn unpack(abi: &Abi, field: &Field, at: usize, text: &mut String) {
    let name = &field.name;
    match &field.ty {
        Type::Array(_, len) => {
            let _ = writeln!(
                text,
                "        for (size_t i = 0; i < {len}; i++) {{\n            results->{name}[i] = radix_results_[{at} + i];\n        }}"
            );
        }
        Type::Prim(Prim::Bool) => {
            let _ = writeln!(text, "        results->{name} = radix_results_[{at}] != 0;");
        }
        other => {
            let _ = writeln!(
                text,
                "        results->{name} = ({})radix_results_[{at}];",
                c_type(abi, other)
            );
        }
    }
}

fn call_code(out: &mut String, abi: &Abi, call: &Call, function: &str, label: Option<u64>) {
    let has_results = !call.results.is_empty();
    if has_results {
        let _ = writeln!(out, "/* The results of {function}. */\nstruct {function}_results {{");
        for field in &call.results {
            let _ = writeln!(out, "    {};", declaration(abi, &field.ty, &field.name));
        }
        out.push_str("};\n\n");
    }
    let mut params = Vec::new();
    let mut names = Vec::new();
    if label.is_some() {
        params.push("uint32_t cap".to_string());
        names.push("cap".to_string());
    }
    for field in &call.args {
        params.push(match &field.ty {
            Type::Array(inner, len) => {
                format!("const {} {}[{len}]", c_type(abi, inner), field.name)
            }
            Type::Bytes(Dir::In) => format!("const void *{0}, size_t {0}_len", field.name),
            Type::Bytes(Dir::Out) => format!("void *{0}, size_t {0}_len", field.name),
            other => declaration(abi, other, &field.name),
        });
        names.push(field.name.clone());
        if matches!(field.ty, Type::Bytes(_)) {
            names.push(format!("{}_len", field.name));
        }
    }
    if has_results {
        params.push(format!("struct {function}_results *results"));
        names.push("results".to_string());
    }
    // The call made with a given function, which the plain form below
    // passes `radix_syscall`.
    let _ = writeln!(out, "/* {function}, made with `radix_syscall_`. */");
    let mut with = vec!["radix_syscall_fn *radix_syscall_".to_string()];
    with.extend(params.iter().cloned());
    let _ = writeln!(out, "static inline uint64_t {function}_with({})\n{{", with.join(", "));
    let base = if label.is_some() { 2 } else { 0 };
    let _ = writeln!(out, "    uint64_t radix_args_[10] = {{0}};");
    let _ = writeln!(out, "    uint64_t radix_results_[10];");
    if let Some(label) = label {
        let count: usize = call.args.iter().map(|f| abi.words(&f.ty)).sum();
        let _ = writeln!(
            out,
            "    radix_args_[0] = cap;\n    radix_args_[1] = UINT64_C({label:#x}) | (UINT64_C({count}) << 32);"
        );
    }
    let mut at = base;
    for field in &call.args {
        pack(abi, field, at, out);
        at += abi.words(&field.ty);
    }
    let number = if label.is_some() {
        "RADIX_SYSCALL_CAP_CALL".to_string()
    } else {
        format!("RADIX_SYSCALL_{}", call.name.to_uppercase())
    };
    let _ = writeln!(
        out,
        "    uint64_t status = radix_syscall_({number}, radix_args_, radix_results_);"
    );
    if has_results {
        out.push_str("    if (status == 0 && results != NULL) {\n");
        let mut at = base;
        for field in &call.results {
            unpack(abi, field, at, out);
            at += abi.words(&field.ty);
        }
        out.push_str("    }\n");
    } else {
        out.push_str("    (void)radix_results_;\n");
    }
    out.push_str("    return status;\n}\n\n");
    comment(out, &call.doc, "");
    if params.is_empty() {
        params.push("void".into());
    }
    let mut args = vec!["radix_syscall".to_string()];
    args.extend(names);
    let _ = writeln!(
        out,
        "static inline uint64_t {function}({})\n{{\n    return {function}_with({});\n}}",
        params.join(", "),
        args.join(", ")
    );
}
