//! The dead keys, made by generate.py from Unicode 15.1.0's
//! canonical compositions: what each makes of each letter.

/// A dead key: an accent put on the next letter typed.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Dead {
    /// `dead:grave`, U+0300.
    Grave,
    /// `dead:acute`, U+0301.
    Acute,
    /// `dead:circumflex`, U+0302.
    Circumflex,
    /// `dead:tilde`, U+0303.
    Tilde,
    /// `dead:macron`, U+0304.
    Macron,
    /// `dead:breve`, U+0306.
    Breve,
    /// `dead:abovedot`, U+0307.
    AboveDot,
    /// `dead:diaeresis`, U+0308.
    Diaeresis,
    /// `dead:hook`, U+0309.
    Hook,
    /// `dead:abovering`, U+030A.
    AboveRing,
    /// `dead:doubleacute`, U+030B.
    DoubleAcute,
    /// `dead:caron`, U+030C.
    Caron,
    /// `dead:horn`, U+031B.
    Horn,
    /// `dead:belowdot`, U+0323.
    BelowDot,
    /// `dead:belowcomma`, U+0326.
    BelowComma,
    /// `dead:cedilla`, U+0327.
    Cedilla,
    /// `dead:ogonek`, U+0328.
    Ogonek,
    /// `dead:belowmacron`, U+0331.
    BelowMacron,
}

impl Dead {
    /// Every dead key.
    pub const ALL: [Dead; 18] = [
        Dead::Grave,
        Dead::Acute,
        Dead::Circumflex,
        Dead::Tilde,
        Dead::Macron,
        Dead::Breve,
        Dead::AboveDot,
        Dead::Diaeresis,
        Dead::Hook,
        Dead::AboveRing,
        Dead::DoubleAcute,
        Dead::Caron,
        Dead::Horn,
        Dead::BelowDot,
        Dead::BelowComma,
        Dead::Cedilla,
        Dead::Ogonek,
        Dead::BelowMacron,
    ];

    /// Its name in a keymap file, after `dead:`.
    pub fn name(self) -> &'static str {
        match self {
            Dead::Grave => "grave",
            Dead::Acute => "acute",
            Dead::Circumflex => "circumflex",
            Dead::Tilde => "tilde",
            Dead::Macron => "macron",
            Dead::Breve => "breve",
            Dead::AboveDot => "abovedot",
            Dead::Diaeresis => "diaeresis",
            Dead::Hook => "hook",
            Dead::AboveRing => "abovering",
            Dead::DoubleAcute => "doubleacute",
            Dead::Caron => "caron",
            Dead::Horn => "horn",
            Dead::BelowDot => "belowdot",
            Dead::BelowComma => "belowcomma",
            Dead::Cedilla => "cedilla",
            Dead::Ogonek => "ogonek",
            Dead::BelowMacron => "belowmacron",
        }
    }

    /// What it types on its own: after a space, or pressed twice.
    pub fn spacing(self) -> char {
        match self {
            Dead::Grave => '\u{60}',
            Dead::Acute => '\u{b4}',
            Dead::Circumflex => '\u{5e}',
            Dead::Tilde => '\u{7e}',
            Dead::Macron => '\u{af}',
            Dead::Breve => '\u{2d8}',
            Dead::AboveDot => '\u{2d9}',
            Dead::Diaeresis => '\u{a8}',
            Dead::Hook => '\u{309}',
            Dead::AboveRing => '\u{2da}',
            Dead::DoubleAcute => '\u{2dd}',
            Dead::Caron => '\u{2c7}',
            Dead::Horn => '\u{31b}',
            Dead::BelowDot => '\u{323}',
            Dead::BelowComma => '\u{2c}',
            Dead::Cedilla => '\u{b8}',
            Dead::Ogonek => '\u{2db}',
            Dead::BelowMacron => '\u{5f}',
        }
    }

    /// Each letter it goes on and what it makes of it, by letter.
    pub(crate) fn letters(self) -> &'static [(char, char)] {
        match self {
            Dead::Grave => GRAVE,
            Dead::Acute => ACUTE,
            Dead::Circumflex => CIRCUMFLEX,
            Dead::Tilde => TILDE,
            Dead::Macron => MACRON,
            Dead::Breve => BREVE,
            Dead::AboveDot => ABOVEDOT,
            Dead::Diaeresis => DIAERESIS,
            Dead::Hook => HOOK,
            Dead::AboveRing => ABOVERING,
            Dead::DoubleAcute => DOUBLEACUTE,
            Dead::Caron => CARON,
            Dead::Horn => HORN,
            Dead::BelowDot => BELOWDOT,
            Dead::BelowComma => BELOWCOMMA,
            Dead::Cedilla => CEDILLA,
            Dead::Ogonek => OGONEK,
            Dead::BelowMacron => BELOWMACRON,
        }
    }
}

